use crate::CliResult;
use serde::Serialize;
use std::collections::BTreeMap;
use wiz_analysis::{
    wizard101::{
        locators::{
            CursorGameSites, CORE, CURSOR_NAME, CURSOR_OVERWRITE_SIZE, CURSOR_SET_EXPORT,
            CURSOR_TARGET_EXPORT, GAME_MODULE, USER32_MODULE,
        },
        Evidence, Finding, Report,
    },
    Result,
};

const HEADER: &str = "# Generated by wiz-extract - DO NOT EDIT MANUALLY!";
const PYTHON_SUPPORT: &str = include_str!("python_support.py");

#[derive(Serialize)]
#[serde(untagged)]
enum Address {
    Rva {
        module: &'static str,
        rva: u32,
    },
    Export {
        module: &'static str,
        symbol: &'static str,
    },
}

#[derive(Serialize)]
struct Hook<'a> {
    target: Address,
    overwrite_size: usize,
    locations: &'a BTreeMap<String, i64>,
    dependencies: BTreeMap<&'a str, Address>,
    evidence: Vec<EvidenceRecord<'a>>,
}

impl<'a> From<&'a Finding> for Hook<'a> {
    fn from(finding: &'a Finding) -> Self {
        let module = finding.module.unwrap_or(GAME_MODULE);
        let dependencies = finding
            .dependencies
            .iter()
            .map(|(name, rva)| {
                let module = finding
                    .dependency_modules
                    .get(name)
                    .copied()
                    .unwrap_or(module);
                (name.as_str(), Address::Rva { module, rva: *rva })
            })
            .collect();
        Self {
            target: Address::Rva {
                module,
                rva: finding.target_rva,
            },
            overwrite_size: finding.overwrite_size,
            locations: &finding.locations,
            dependencies,
            evidence: finding.evidence.iter().map(EvidenceRecord::from).collect(),
        }
    }
}

impl<'a> Hook<'a> {
    fn cursor(sites: &'a CursorGameSites, locations: &'a BTreeMap<String, i64>) -> Self {
        let mut dependencies: BTreeMap<_, _> = sites
            .flag_rvas
            .iter()
            .map(|(name, rva)| {
                (
                    name.as_str(),
                    Address::Rva {
                        module: GAME_MODULE,
                        rva: *rva,
                    },
                )
            })
            .collect();
        dependencies.insert(
            "set_cursor_pos",
            Address::Export {
                module: USER32_MODULE,
                symbol: CURSOR_SET_EXPORT,
            },
        );
        Self {
            target: Address::Export {
                module: USER32_MODULE,
                symbol: CURSOR_TARGET_EXPORT,
            },
            overwrite_size: CURSOR_OVERWRITE_SIZE,
            locations,
            dependencies,
            evidence: sites.evidence.iter().map(EvidenceRecord::from).collect(),
        }
    }
}

pub fn generate(
    report: &Report,
    game_sha256: &str,
    cursor: Result<CursorGameSites>,
) -> CliResult<String> {
    let missing: Vec<_> = CORE
        .iter()
        .filter(|spec| {
            !report
                .hooks
                .get(spec.name)
                .is_some_and(|entry| entry.finding.is_some())
        })
        .map(|spec| spec.name)
        .collect();
    if !missing.is_empty() {
        return Err(format!(
            "Can't generate generated/wiz_hooks.py. Required hooks are unresolved ({}).",
            missing.join(", "),
        )
        .into());
    }

    let mut hooks = BTreeMap::new();
    let mut unavailable = BTreeMap::new();
    for (name, entry) in &report.hooks {
        if name == CURSOR_NAME {
            continue;
        }
        if let Some(finding) = &entry.finding {
            hooks.insert(name.as_str(), Hook::from(finding));
        } else if let Some(error) = &entry.error {
            unavailable.insert(name.as_str(), error.message.as_str());
        }
    }

    let empty_locations = BTreeMap::new();
    match &cursor {
        Ok(sites) => {
            hooks.insert(CURSOR_NAME, Hook::cursor(sites, &empty_locations));
        }
        Err(error) => {
            unavailable.insert(CURSOR_NAME, error.message.as_str());
        }
    }

    let game_sha256 = python_literal(&game_sha256)?;
    let hooks = python_literal(&hooks)?;
    let unavailable = python_literal(&unavailable)?;
    Ok(format!(
        "{HEADER}\n{PYTHON_SUPPORT}\n\nGAME_SHA256 = {game_sha256}\nRESOLVER_VERSION = {}\n\n\
         HOOKS: dict[str, HookDef] = _build_hooks({hooks})\n\n\
         UNAVAILABLE: dict[str, str] = {unavailable}\n",
        report.resolver_version,
    ))
}

#[derive(Serialize)]
struct EvidenceRecord<'a> {
    address: Address,
    data: Vec<String>,
    role: &'a str,
}

impl<'a> From<&'a Evidence> for EvidenceRecord<'a> {
    fn from(proof: &'a Evidence) -> Self {
        Self {
            address: Address::Rva {
                module: proof.module.unwrap_or(GAME_MODULE),
                rva: proof.rva,
            },
            data: proof.bytes.chunks(32).map(hex_bytes).collect(),
            role: &proof.role,
        }
    }
}

fn python_literal(value: &impl Serialize) -> CliResult<String> {
    // JSON output for strings, integers, lists, and dictionaries is valid Python syntax.
    let mut bytes = Vec::new();
    let formatter = serde_json::ser::PrettyFormatter::with_indent(b"    ");
    value.serialize(&mut serde_json::Serializer::with_formatter(
        &mut bytes, formatter,
    ))?;
    Ok(String::from_utf8(bytes)?)
}

fn hex_bytes(bytes: &[u8]) -> String {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    let mut encoded = String::with_capacity(bytes.len() * 2);
    for &byte in bytes {
        encoded.push(char::from(DIGITS[usize::from(byte >> 4)]));
        encoded.push(char::from(DIGITS[usize::from(byte & 0x0f)]));
    }
    encoded
}

#[cfg(test)]
mod tests {
    use super::*;
    use wiz_analysis::{wizard101::Availability, Error};

    #[test]
    fn requires_core_hooks_and_keeps_cursor_exports_portable() {
        let mut report = Report {
            schema_version: 1,
            resolver_version: 2,
            image_size: 0x1000,
            timestamp: 0,
            hooks: BTreeMap::new(),
        };
        let cursor = || {
            Ok(CursorGameSites {
                flag_rvas: BTreeMap::from([("cursor_flag_one".into(), 0x200)]),
                evidence: vec![Evidence {
                    module: None,
                    rva: 0x1fd,
                    bytes: vec![0, 0xff],
                    role: "flag proof".into(),
                }],
            })
        };
        assert!(generate(&report, "build-hash", cursor())
            .unwrap_err()
            .to_string()
            .contains("core.client"));

        for spec in CORE {
            report.hooks.insert(
                spec.name.into(),
                Availability::from(Ok(Finding {
                    module: None,
                    target_rva: 0x100,
                    overwrite_size: 5,
                    locations: BTreeMap::new(),
                    dependencies: BTreeMap::new(),
                    dependency_modules: BTreeMap::new(),
                    evidence: Vec::new(),
                })),
            );
        }
        report.hooks.insert(
            CURSOR_NAME.into(),
            Availability::from(Err(Error::new(CURSOR_NAME, "missing DLL"))),
        );
        report.hooks.insert(
            "drops_toggle".into(),
            Availability::from(Err(Error::new("drops_toggle", "No match for \"drops\".\n"))),
        );
        let generated = generate(&report, "build-hash", cursor()).unwrap();
        assert!(generated.contains("\"symbol\": \"GetCursorPos\""));
        assert!(generated.contains("\"symbol\": \"SetCursorPos\""));
        assert!(generated.contains("\"rva\": 509"));
        assert!(generated.contains("\"00ff\""));
        assert!(generated.contains("\"drops_toggle\": \"No match for \\\"drops\\\".\\n\""));
        assert!(!generated.contains("missing DLL"));
        assert!(generated.starts_with("# Generated by wiz-extract - DO NOT EDIT MANUALLY!\n"));
        assert!(generated.ends_with("}\n"));
    }
}
